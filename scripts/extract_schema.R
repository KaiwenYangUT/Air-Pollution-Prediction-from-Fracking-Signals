#!/usr/bin/env Rscript
# Writes docs/data_dictionary.md with ONLY: file name, size, row count, column names, dtypes.
# PRIVACY: never prints/writes values, head(), unique levels, ranges or summary stats.
# All warnings/messages are suppressed because fread warnings can quote raw lines.
# Covers <data_root>/raw and <data_root>/processed (the legacy derived data).
suppressPackageStartupMessages(library(data.table))
source("R/config.R")
root <- cfg$data_root
out  <- "docs/data_dictionary.md"
n_fail <- 0L

quiet <- function(expr) tryCatch(suppressWarnings(suppressMessages(expr)),
                                 error = function(e) { n_fail <<- n_fail + 1L; NULL })
size_mb <- function(f) sprintf("%.1f MB", file.size(f) / 1024^2)
rel <- function(f) sub(paste0("^", normalizePath(root), "/"), "", normalizePath(f))
col_tbl <- function(nm, ty) c("| column | dtype |", "|---|---|", sprintf("| `%s` | %s |", nm, ty))
df_schema <- function(x) list(rows = nrow(x), names = names(x),
                              types = vapply(x, function(v) class(v)[1], ""))
scan_dirs <- file.path(root, c("raw", "processed"))

lines <- c("# Data dictionary", "",
           "Generated by `scripts/extract_schema.R`. Structure only — no data values.",
           "Paths are relative to `data_root` in config.yml (outside the repo).", "")

# --- CSV: names from header, rows via 1-column read, dtypes inferred from first 100k rows
for (f in list.files(scan_dirs, "\\.csv$", recursive = TRUE, full.names = TRUE)) {
  hdr <- quiet(names(fread(f, nrows = 0L)))
  n   <- quiet(nrow(fread(f, select = 1L, showProgress = FALSE)))
  ty  <- quiet(vapply(fread(f, nrows = 100000L, showProgress = FALSE), function(v) class(v)[1], ""))
  lines <- c(lines, sprintf("## `%s`", rel(f)),
             sprintf("- size: %s; rows: %s; columns: %s (dtypes inferred from first 100k rows)",
                     size_mb(f), if (is.null(n)) "unreadable" else n, length(hdr)), "",
             if (!is.null(hdr) && !is.null(ty)) col_tbl(hdr, ty) else "_could not parse (error suppressed)_", "")
}

# --- .rdata / .rds: exact classes from the stored objects
for (f in list.files(scan_dirs, "\\.(rdata|RData|rds)$", recursive = TRUE, full.names = TRUE)) {
  objs <- if (grepl("\\.rds$", f)) list(readRDS = quiet(readRDS(f))) else {
    e <- new.env(); nm <- quiet(load(f, envir = e)); mget(nm %||% character(), envir = e) }
  lines <- c(lines, sprintf("## `%s` (%s)", rel(f), size_mb(f)), "")
  for (o in names(objs)) {
    x <- objs[[o]]
    if (is.data.frame(x)) { s <- df_schema(x)
      lines <- c(lines, sprintf("### object `%s` — class %s; rows: %d; columns: %d",
                                o, class(x)[1], s$rows, length(s$names)), "", col_tbl(s$names, s$types), "")
    } else lines <- c(lines, sprintf("### object `%s` — class %s (not tabular)", o, class(x)[1]), "")
  }
  rm(objs); invisible(gc(verbose = FALSE))
}

# --- Raw sound logs: only LoggedBB/LoggedSpectra (the files the pipeline reads) get column schemas,
#     read exactly as the pipeline does (fread fill=TRUE). Other .txt files (Total*, Setup,
#     LNMxxx.txt — possibly key:value metadata whose "headers" could be values) get size + line count only.
sound <- list.files(file.path(root, "raw/sound"), "\\.txt$", recursive = TRUE, full.names = TRUE)
for (type in c("LoggedBB", "LoggedSpectra")) {
  fs <- grep(paste0("_", type, "\\.txt$"), sound, value = TRUE)
  per <- lapply(fs, function(f) quiet(fread(f, fill = TRUE, nrows = 10000L, showProgress = FALSE)))
  ok  <- !vapply(per, is.null, TRUE)
  all_cols <- unique(unlist(lapply(per[ok], names)))
  n_with   <- vapply(all_cols, function(cn) sum(vapply(per[ok], function(d) cn %in% names(d), TRUE)), 0L)
  ty       <- vapply(all_cols, function(cn) paste(unique(unlist(lapply(per[ok], function(d)
                if (cn %in% names(d)) class(d[[cn]])[1]))), collapse = "/"), "")
  rows <- vapply(fs, function(f) { r <- quiet(nrow(fread(f, fill = TRUE, select = 1L, showProgress = FALSE)))
                                   if (is.null(r)) NA_integer_ else r }, 0L)
  lines <- c(lines, sprintf("## Raw sound: `*_%s.txt` (%d files, %d unparseable)", type, length(fs), sum(!ok)), "",
             "| column | dtype | files containing |", "|---|---|---|",
             sprintf("| `%s` | %s | %d |", all_cols, ty, n_with), "",
             "| file | size | rows |", "|---|---|---|",
             sprintf("| `%s` | %s | %s |", vapply(fs, rel, ""), vapply(fs, size_mb, ""), rows), "")
  rm(per); invisible(gc(verbose = FALSE))
}
other <- setdiff(sound, grep("_Logged(BB|Spectra)\\.txt$", sound, value = TRUE))
wc <- vapply(other, function(f) as.integer(strsplit(trimws(system2("wc", c("-l", shQuote(f)), stdout = TRUE)), " +")[[1]][1]), 0L)
lines <- c(lines, "## Raw sound: other files (structure not inspected)", "", "| file | size | lines |", "|---|---|---|",
           sprintf("| `%s` | %s | %d |", vapply(other, rel, ""), vapply(other, size_mb, ""), wc), "")

dir.create("docs", showWarnings = FALSE)
writeLines(lines, out)
cat(sprintf("Wrote %s (%d parse failures, messages suppressed)\n", out, n_fail))
